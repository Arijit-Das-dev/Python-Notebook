# ==========================
# Type Casting
# ==========================


# int to str
num = 12
print(str(num))

# str to int
text = "12"
print(int(text))

# error -> ValueError: invalid literal for int() with base 10: 'ar'
text2 = "ar"
print(int(text2))

# int to float
num = 12
print(float(num))

# float to int
num2 = 12.190
print(int(num2))