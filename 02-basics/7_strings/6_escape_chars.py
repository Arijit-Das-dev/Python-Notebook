# ==========================
# Escape Characters
# ==========================

# \'	    Single Quote	
# \\	    Backslash	
# \n	    New Line	
# \r	    Carriage Return	
# \t	    Tab	
# \b	    Backspace	
# \f	    Form Feed	


# \'        Single Quote
print('Hi it\'s John')

# \\	    Backslash
print("One \\ Backslash")
print("Two \\\ Backslash")

# \n	    New Line
print("Hi\n My name is John")

# \r	    Carriage Return	
txt = "Hello\rWorld!"
print(txt)

# \t	    Tab
print("A\tB\tC")

# \b	    Backspace
print("A \b C")

# \f	    Form Feed
print("A \f C")