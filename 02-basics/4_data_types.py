"""
Types :

    Numeric type : int, float, complex
    Text type : str
    Boolean type : Bool [True, False]
    Sequence type = List, tuple, range
    Mapping type = dict
    Set type = set

"""

# Numeric type 
num1 = 12           # int
print(type(num1))

num2 = 1.0          # float
print(type(num2))

num = 3j            # complex
print(type(num))


# Text type 
name = "John Doe"   # str
print(type(name))

# Boolean Type 
is_True = True
is_False = False


# Sequence type
arr = [1, 2, 3, 4]  # list
print(type(arr))

nums = {1, 2, 3, 4} # set
print(type(nums))


# mapping type
data = {
    "name":"Arijit",
    "id":12
}
print((data))


# set type
x = (1, 2, 3, 4)
print(type(x))