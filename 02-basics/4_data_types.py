num1 = 12           # int
print(type(num1))

num2 = 1.0          # float
print(type(num2))

num = 3j            # complex
print(type(num))


# Text type 
name = "John Doe"   # str
print(type(name))

# Boolean Type 
is_True = True
is_False = False


