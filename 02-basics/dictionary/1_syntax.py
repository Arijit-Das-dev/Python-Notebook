"""
dict = {
    key : value
}
"""
students = {
    "id":1,
    "name":"John",
    "dept":"BCA",
    "sec":"A",
}
print(students)

# count how many keys are present 
print(len(students))    # 4

# check type 
print(type(students))   # <class 'dict'>